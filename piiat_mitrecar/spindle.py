def _yaml(doc: dict) -> str:
    return yaml.safe_dump(doc, sort_keys=False, default_flow_style=False,
                          allow_unicode=True, width=100)


def render(filename: str) -> str:
    return _HEADER.format(what=_WHAT[filename]) + _yaml(_DOCS[filename]())


def verify_golden(out_dir: str) -> list[str]:
    """The change protocol over the COMMITTED golden.yml against a fresh
    rendering; [] when every move is legitimate. Per entry (and for the
    positional vector) the guid and the version must move together: a guid
    that moved at the same version is an identity change without a bump; a
    version that moved without its guid cannot be a fresh mint. The recipe
    vector must not move at all — that moves every guid. A missing file, or
    an entry the committed table does not know, is not drift here
    (verify_snapshot reports the file); an external form has no version — a
    moved external vector is plain snapshot drift, and the form itself is
    held to the maps by verify_registry."""
    path = os.path.join(out_dir, GOLDEN_FILE)
    if not os.path.exists(path):
        return []
    with open(path, encoding="utf-8") as fh:
        committed = yaml.safe_load(fh) or {}
    fresh = golden_doc()
    problems: list[str] = []
    if (committed.get("spindle") or {}).get("recipe") != fresh["spindle"]["recipe"]:
        problems.append(f"{GOLDEN_FILE}: the recipe vector moved (canonical_json or a namespace) — "
                        "every guid re-mints: that is a new spindle, not an entry version bump")
    have = {e.get("name"): e for e in committed.get("identities") or [] if isinstance(e, dict)}
    want = {e["name"]: e for e in fresh["identities"]}
    pairs = [("positional", committed.get("positional"), fresh["positional"])]
    pairs += [(n, have[n], want[n]) for n in sorted(set(have) & set(want))]
    for name, old, new in pairs:
        if not isinstance(old, dict):
            continue
        guid_moved, version_moved = old.get("guid") != new["guid"], old.get("version") != new["version"]
        if guid_moved and not version_moved:
            problems.append(f"{name}: golden guid moved at version {new['version']} — the identity (fields, "
                            "names, rendering, recipe or golden sample) changed without a version bump: "
                            "bump `version`, then regenerate")
        elif version_moved and not guid_moved:
            problems.append(f"{name}: version moved {old.get('version')} -> {new['version']} but the golden "
                            "guid did not — _v is hashed, so a bump always re-mints; the committed vector is stale")
    return problems


def write_snapshot(out_dir: str) -> list[str]:
    """Write the snapshot files. Refuses (ValueError) while the committed
    golden table says an identity changed without its version bump — the
    change protocol's gate — so a regenerate can never launder such a change."""
    problems = verify_golden(out_dir)
    if problems:
        raise ValueError("the golden vectors refuse this regenerate:\n  - " + "\n  - ".join(problems))
    os.makedirs(out_dir, exist_ok=True)
    written = []
    for filename in FILES:
        path = os.path.join(out_dir, filename)
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(render(filename))
        written.append(path)
    return written


def verify_snapshot(out_dir: str) -> list[str]:
    """The committed snapshot against a fresh rendering; [] when in sync."""
    problems = []
    for filename in FILES:
        path = os.path.join(out_dir, filename)
        if not os.path.exists(path):
            problems.append(f"{path}: missing (run python model/generate.py)")
            continue
        with open(path, encoding="utf-8") as fh:
            if fh.read() != render(filename):
                problems.append(f"{path}: drifted from the registry / maps / engine (run python model/generate.py)")
    return problems


