def _native_of(ev: dict) -> dict:
    nat = ev.get("_native") if "_native" in ev else ev.get("native")
    return nat if isinstance(nat, dict) else {}


def entry_of(ev: dict) -> dict | None:
    """The registry entry a minted row was minted under: the entry of the
    row's artefact, for its object, whose identity names and version are the
    key's — None for a positional row, an external-form row, or a key that
    matches no entry."""
    key = _native_of(ev).get(NATIVE_KEY)
    if not isinstance(key, dict):
        return None
    names = set(key) - set(ids.RESERVED_KEYS)
    version, obj, art = key.get(ids.VERSION_KEY), ev.get("car_object"), str(ev.get("source_artefact"))
    for n, e in identities().items():
        if (n == art or n.startswith(art + "/")) and e.get("object") == obj \
                and {f for f, _s, _m in identity_fields(e)} == names and e.get("version") == version:
            return e
    return None


def equatable_across_sources(ev: dict) -> bool:
    """The #41 predicate (spindle.yml `equality`): whether a row MAY be equated
    with a row of another source by exact (case, source_host, car_object,
    guid). True when the row carries a guid and either its identity is a
    spindle of scope intrinsic minted under an entry of kind record | entity,
    or it is an external form — a sensor's or tool's own id, equated by exact
    value. A positional identity never is, nor is a guid-less row. The pair
    rule (both rows pass this, equal _v) is the consumer's — #41 PR B."""
    if ev.get("guid") in (None, ""):
        return False
    nat = _native_of(ev)
    if NATIVE_KEY not in nat and NATIVE_SCOPE not in nat:
        return True                              # an external form: exact value
    if nat.get(NATIVE_SCOPE) != INTRINSIC:
        return False
    e = entry_of(ev)
    return e is not None and e.get("kind") in KINDS


def validate_record(ev: dict) -> list[str]:
    """Every way a row fails to be a well-formed spindle; [] means it is one:
    the guid re-mints from its own native.spindle_key, the key names the row's
    object, carries the entry's version and the entry's identity names (or the
    positional fields at the positional version), the scope is in the vocabulary."""
    problems: list[str] = []
    nat = _native_of(ev)
    obj, guid = ev.get("car_object"), ev.get("guid")
    key, scope = nat.get(NATIVE_KEY), nat.get(NATIVE_SCOPE)
    if not isinstance(key, dict) or ids.OBJECT_KEY not in key:
        return [f"native.{NATIVE_KEY}: missing, or not a dict carrying {ids.OBJECT_KEY!r}"]
    if key[ids.OBJECT_KEY] != obj:
        problems.append(f"native.{NATIVE_KEY}.{ids.OBJECT_KEY} {key[ids.OBJECT_KEY]!r} != car_object {obj!r}")
    version = key.get(ids.VERSION_KEY)
    if not isinstance(version, int) or isinstance(version, bool):
        problems.append(f"native.{NATIVE_KEY}.{ids.VERSION_KEY}: missing or not an int (the identity-key version)")
    if any(not isinstance(v, str) for k, v in key.items() if k not in ids.RESERVED_KEYS):
        problems.append(f"native.{NATIVE_KEY}: every value contributes in its string rendering")
    if scope not in SCOPES:
        problems.append(f"native.{NATIVE_SCOPE} {scope!r} is not one of {list(SCOPES)}")
    try:
        minted = isinstance(guid, str) and uuid.UUID(guid).version == 5
    except ValueError:
        minted = False
    if not minted:
        problems.append("guid: not a version-5 UUID string")
    elif guid != ids.guid_of(key):
        problems.append(f"guid: does not re-mint from native.{NATIVE_KEY}")
    names = set(key) - set(ids.RESERVED_KEYS)
    if scope == POSITIONAL:
        if names != set(positional()):
            problems.append(f"a positional key carries exactly the positional fields {positional()}")
        if version != positional_version():
            problems.append(f"a positional key carries the positional version {positional_version()}, not {version!r}")
    if scope == INTRINSIC and entry_of(ev) is None:
        problems.append(f"native.{NATIVE_KEY} names {sorted(names)} at version {version!r} match no "
                        f"registry entry of {ev.get('source_artefact')!r} for {obj!r}")
    return problems


