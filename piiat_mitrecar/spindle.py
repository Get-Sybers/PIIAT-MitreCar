def golden_doc() -> dict:
    """golden.yml: the pinned vectors — for every entry the key and the guid
    ids.mint yields for its golden sample at the entry's version, the
    positional vector, one vector per external form (rendered through the
    engine's own path), and the recipe vector (canonical_json over a fixed
    input + the three namespaces). The change protocol's evidence: an
    identity change moves an entry's guid, a recipe change moves them all."""
    spec = rules()["spindle"]
    pos = spec["positional"]
    pguid, pkey = positional_vector()
    entries = []
    for name in sorted(identities()):
        e = identities()[name]
        guid, key = golden_vector(e["object"], e)
        entries.append({"name": name, "kind": e.get("kind"), "version": e["version"],
                        "source": golden(e).get("source"), "key": key, "guid": guid})
    external = []
    for name in sorted(externals()):
        e = externals()[name]
        g = golden(e)
        external.append({"name": name, "kind": e.get("kind"), "source": g.get("source"),
                         "car_object": g.get("object"), "values": dict(g.get("values") or {}),
                         "guid": external_vector(e)})
    return {
        "spindle": {
            "version": spec.get("version"),
            "recipe": {
                "canonical_json": {"input": dict(RECIPE_INPUT), "output": ids.canonical_json(RECIPE_INPUT)},
                "namespaces": {"STIX_NS": str(ids.STIX_NS), "CAR_NS": str(ids.CAR_NS),
                               "SPINDLE_NS": str(ids.SPINDLE_NS)},
                "mint": "guid = uuid5(SPINDLE_NS, canonical_json(key))",
            },
        },
        "positional": {"version": pos["version"], "fields": list(pos["fields"]),
                       "source": (pos.get("golden") or {}).get("source"), "key": pkey, "guid": pguid},
        "identities": entries,
        "external": external,
    }


